import ExcelJS from "exceljs";


const SURNAMES = ["Тестов", "Пробный", "Образцов", "Примеров", "Условный", "Демонстров", "Шаблонов", "Модельный", "Синтетиков", "Вымыслов"];
const NAMES = ["Иван", "Пётр", "Анна", "Мария", "Олег", "Елена", "Сергей", "Ольга"];
const STREETS = ["ул. Учебная", "пр. Тестовый", "ул. Пробная", "пер. Образцовый", "ул. Условная"];

const person = (i: number) => `${SURNAMES[i % SURNAMES.length]} ${NAMES[i % NAMES.length]}`;
const phone = (i: number) => `8 (900) 1${String(i).padStart(2, "0")}-${String(10 + (i % 80)).padStart(2, "0")}-${String(20 + (i % 70)).padStart(2, "0")}`;
const address = (i: number) => `${STREETS[i % STREETS.length]}, д. ${10 + i}`;

export async function buildSampleWorkbook(): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Лист1");
  const add = (values: (string | number | Date | null)[]) => ws.addRow(values);
  const blank = () => ws.addRow([]);

  add(["База агентства — СИНТЕТИЧЕСКИЙ образец для проверки импорта"]);
  add(["Служебный комментарий: данные вымышлены"]);
  blank();

  
  add(["Архив сделок (историческая база)"]);
  add(["№", "Дата сделки", "Жилая/коммерческая", "Адрес", "Комнаты/тип помещения", "Участник сделки", "ФИО", "Дата рождения", "Паспорт", "Выдан", "Регистрация", "Телефон", "Этаж/этажность", "Площадь", "Стоимость", "Условия продажи", "Риелтор", "Информационный договор", "Сумма комиссии", "Фактическое поступление", "Доп. информация"]);
  for (let i = 1; i <= 32; i++) {
    const date = i === 7 ? "31.02.2015" : new Date(Date.UTC(2012 + (i % 10), i % 12, 1 + (i % 27)));
    add([
      i,
      date,
      i % 3 === 0 ? "коммерческая" : "жилая",
      i === 12 ? null : address(i),
      i % 3 === 0 ? "офис" : `${1 + (i % 4)}-комн.`,
      i % 2 ? "покупатель" : "продавец",
      i === 12 ? null : person(i),
      "01.01.1980",
      "0000 000000",
      "ОТДЕЛОМ ТЕСТОВОГО УФМС",
      "г. Тестовск, ул. Регистрационная, 1",
      i === 5 ? "не указан" : phone(i),
      `${1 + (i % 9)}/9`,
      40 + i,
      i === 9 ? "договорная" : 3_000_000 + i * 50_000,
      i % 2 ? "ипотека" : "наличные",
      i % 2 ? "Риелтор 1" : "Риелтор 2",
      i % 4 ? "есть" : "нет",
      60_000 + i * 1000,
      i % 5 ? "получено" : "",
      i === 3 ? "повторная сделка" : null,
    ]);
  }
  blank();
  add(["Комментарий: строки ниже — рабочие объекты"]);
  blank();

  
  add(["Реклама: коммерческая аренда"]);
  add(["Адрес", "Район", "Площадь", "Цена", "Этаж", "Назначение", "Описание", "Рекл. текст", "Реклама", "Собственник", "Телефон собственника", "ОВ", "ЗУ"]);
  for (let i = 1; i <= 5; i++) {
    add([address(100 + i), i % 2 ? "Центральный" : "Северный", 50 + i * 10, 60_000 + i * 5000, i, "торговля", i === 2 ? "Светлое помещение, звоните 8 900 123-45-67" : "Помещение на первой линии", "Сдаётся помещение свободного назначения", i === 3 ? "не ссылка" : `https://example.invalid/ads/${i}`, `${person(50 + i)}`, i === 4 ? "" : phone(50 + i), "да", i === 1 ? "есть" : ""]);
  }
  blank();

  
  add(["Реклама: коммерческая продажа"]);
  add(["Адрес", "Площадь", "Цена", "Этаж", "Описание", "Реклама"]);
  for (let i = 1; i <= 3; i++) add([address(200 + i), 120 + i, 9_000_000 + i * 100_000, 1, "Отдельный вход", `https://example.invalid/sale/${i}`]);
  
  add([address(201), 121, 9_100_000, 1, "Дубль строки для проверки", null]);
  blank();

  
  add(["Жилая продажа"]);
  add(["Адрес", "Площадь", "Цена", "Комнаты", "Этаж", "Этажность"]);
  add([address(300), 54, 6_500_000, 2, 5, 9]);
  add([address(301), 38, "договорная", 1, 2, 5]);
  add([null, 70, 8_000_000, 3, 7, 12]);
  blank();

  
  add(["Текущая клиентская база (входящие звонки)"]);
  add(["Дата поступления", "Дата обновления", "Отметка о состоянии", "Функция", "Имя", "Координаты", "Комментарии"]);
  for (let i = 1; i <= 22; i++) {
    add([
      i === 4 ? "вчера" : new Date(Date.UTC(2026, 8, 1 + i)),
      new Date(Date.UTC(2026, 9, 1 + (i % 20))),
      i % 7 === 0 ? "неактуально" : i % 11 === 0 ? "сделка" : "актуально",
      i % 3 === 0 ? "покупка" : i % 5 === 0 ? "универсал" : "аренда",
      i === 15 ? null : person(70 + i),
      i === 18 ? phone(71) : i === 20 ? `client${i}@example.invalid` : phone(70 + i),
      i === 2 ? "Ищет помещение до 100 м²" : null,
    ]);
  }
  blank();

  
  add(["Анализ договоров и качества рекламы"]);
  add(["Актуальность", "Задача", "Адрес", "Площадь", "Цена", "Рекл. текст", "Реклама", "Наличие договора", "Причины, почему его нет", "Комиссия от", "Комиссия до", "Что нужно исправить"]);
  add(["актуально", "обновить фото", address(101), 60, 65_000, "Текст объявления", "https://example.invalid/ads/1", "нет", "собственник отказался", 50, 100, "Переснять фото"]);
  add(["актуально", null, address(400), 80, 90_000, null, null, "да", null, 50, 100, null]);
  add(["не актуально", null, address(401), 45, 40_000, null, "https://example.invalid/ads/9", "?", null, null, null, "Снять объявление"]);
  blank();

  
  add(["Общая база объектов из рекламы"]);
  add(["Адрес", "Тип", "Операция", "Площадь", "Цена", "Площадка", "Реклама"]);
  add([address(500), "офис", "аренда", 30, 35_000, "Авито", "https://example.invalid/ext/1"]);
  add([address(501), "квартира", "продажа", 44, 5_200_000, "ЦИАН", "https://example.invalid/ext/2"]);
  add([address(502), "непонятно", "обмен", 10, 1000, null, null]);
  blank();

  
  add(["Коммерческая аренда (старый формат)"]);
  add(["Объект", "Метраж", "Сумма"]);
  add(["Старая запись", 10, 100]);

  wb.addWorksheet("Лист2");
  return Buffer.from(await wb.xlsx.writeBuffer());
}
