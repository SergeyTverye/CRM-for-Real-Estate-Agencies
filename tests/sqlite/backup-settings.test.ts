import { afterAll, beforeAll, expect, it } from "vitest";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { GET, PUT } from "@/app/api/v1/settings/backups/route";
import { defaultSettings } from "@/modules/desktop-backup/domain/settings";
import { disconnectDb } from "@/shared/db/client";
import { apiRequest, routeParams, seedBase, sessionCookieFor, type TestUsers } from "../helpers/fixtures";
let users: TestUsers; let root: string; const originalDir = process.env.BACKUP_SETTINGS_DIR;
beforeAll(async () => { root = await mkdtemp(path.join(os.tmpdir(), "crm-sqlite-backup-settings-")); process.env.BACKUP_SETTINGS_DIR = root; users = await seedBase(); });
afterAll(async () => { await disconnectDb(); if (originalDir === undefined) delete process.env.BACKUP_SETTINGS_DIR; else process.env.BACKUP_SETTINGS_DIR = originalDir; await rm(root, { recursive: true, force: true }); });
it("SQLite sessions protect manager-only settings and DPAPI credentials; direct realtor URL denied", async () => {
  expect((await GET(apiRequest("GET", "/api/v1/settings/backups"), routeParams({}))).status).toBe(401);
  const realtor = await sessionCookieFor(users.realtor1);
  expect((await GET(apiRequest("GET", "/api/v1/settings/backups", { cookie: realtor }), routeParams({}))).status).toBe(403);
  expect((await PUT(apiRequest("PUT", "/api/v1/settings/backups", { cookie: realtor, body: {} }), routeParams({}))).status).toBe(403);
  const cookie = await sessionCookieFor(users.manager);
  const read = await GET(apiRequest("GET", "/api/v1/settings/backups", { cookie }), routeParams({})); expect(read.status).toBe(200);
  const dto = await read.json(); expect(dto.secretStorage.protection).toBe("windows-dpapi-current-user");
  const initial = defaultSettings();
  const local = { id: randomUUID(), kind: "local", enabled: true, directory: root };
  const destinations: unknown[] = [local];
  if (process.platform === "win32") destinations.push({ id: randomUUID(), kind: "mailru_webdav", enabled: true, email: "synthetic@example.invalid", prefix: "synthetic", endpoint: "https://webdav.cloud.mail.ru", partBytes: 1024 ** 2, useMove: true, applicationPassword: "synthetic-dpapi-api-only" });
  const body = { expectedUpdatedAt: dto.updatedAt, schedule: initial.schedule, retention: initial.retention, destinations };
  const update = await PUT(apiRequest("PUT", "/api/v1/settings/backups", { cookie, body }), routeParams({})); expect(update.status).toBe(200);
  expect(await update.text()).not.toContain("synthetic-dpapi-api-only");
  expect((await PUT(apiRequest("PUT", "/api/v1/settings/backups", { cookie, body }), routeParams({}))).status).toBe(409);
});
