import { beforeEach, describe, expect, it } from "vitest";
import { db, resetDatabase, seedBase, makeClient, makeNeed, makeProperty, type TestUsers, apiRequest, sessionCookieFor, routeParams } from "../helpers/fixtures";
import { createTask } from "@/modules/tasks/application/task-service";
import { countOverdueTasks, getTodayView, listTasks, listTasksLinkedTo } from "@/modules/tasks/application/task-queries";
import { scheduleShowing } from "@/modules/showings/application/showing-service";
import { generateNotifications } from "@/modules/notifications/application/notification-generator";
import { listNotifications } from "@/modules/notifications/application/notification-service";
import { getCalendarEvent, listCalendar, pickCalendarLinks, saveCalendarEvent } from "@/modules/calendar/application/calendar-service";
import { getClientRecentInteractions } from "@/modules/clients/application/client-queries";
import { GET as linksGET } from "@/app/api/v1/calendar/links/route";
import { startOfDayInTz } from "@/shared/time";

describe("P1 calendar, today, notification and client UX", () => {
  let users: TestUsers;
  beforeEach(async () => { await resetDatabase(); users = await seedBase(); });
  it("saves intersecting meetings with a clear warning that reveals no competing title", async () => {
    const start = new Date(), end = new Date(+start + 3600000);
    await saveCalendarEvent(users.realtor1, { title: "Частная запись", startAt: start.toISOString(), endAt: end.toISOString() });
    const overlapping = await saveCalendarEvent(users.realtor1, { title: "Новая встреча", startAt: new Date(+start + 60000).toISOString(), endAt: end.toISOString() });
    expect(overlapping.warning).toContain("Встреча сохранена");
    expect(overlapping.warning).toContain("перенесите");
    expect(overlapping.warning).not.toContain("Частная запись");
    expect(await db.calendarEvent.count()).toBe(2);
  });
  it("agrees across header, today, drill-down, scopes and showing helper tasks", async () => {
    const c = await makeClient(users.realtor1), n = await makeNeed(users.realtor1, c.id), p = await makeProperty(users.realtor1);
    const now = new Date(), tomorrow = new Date(+startOfDayInTz(now, "Asia/Novosibirsk") + 86400000);
    await createTask(users.realtor1, { title: "Просроченный звонок", taskType: "call_or_contact", dueAt: new Date(+now - 3600000).toISOString() });
    await createTask(users.realtor2, { title: "Чужая задача", taskType: "other", dueAt: new Date(+now - 3600000).toISOString() });
    const s = await scheduleShowing(users.realtor1, { clientNeedId: n.id, propertyId: p.id, scheduledAt: new Date((+now + +tomorrow) / 2).toISOString() });
    await db.task.update({ where: { id: s.taskId }, data: { dueAt: new Date(+now - 60000) } });
    const mine = await getTodayView(users.realtor1);
    expect(mine.counters.overdue).toBe(1);
    expect(mine.counters.overdue).toBe(mine.overdue.length);
    expect(mine.counters.overdue).toBe(await countOverdueTasks(users.realtor1));
    expect((await listTasks(users.realtor1, { view: "overdue" })).total).toBe(mine.counters.overdue);
    expect(mine.counters.today).toBe(Object.values(mine.today).flat().length);
    expect(mine.counters.showingsToday).toBe(1);
    expect(mine.showingsToday.map(s => s.id)).toContain(s.id);
    const all = await getTodayView(users.manager, { scope: "all" });
    expect(all.counters.overdue).toBe(2);
    const one = await getTodayView(users.manager, { userId: users.realtor1.userId });
    expect(one.counters).toEqual(mine.counters);
  });
  it("picker API hides foreign client, need and deal links; reopening retains names", async () => {
    const own = await makeClient(users.realtor1, { displayName: "Доступный клиент" }), foreign = await makeClient(users.realtor2, { displayName: "Скрытый клиент" });
    const ownNeed = await makeNeed(users.realtor1, own.id), foreignNeed = await makeNeed(users.realtor2, foreign.id);
    const p = await makeProperty(users.realtor1);
    await db.deal.create({ data: { propertyId: p.id, createdBy: users.realtor1.userId, responsibleUserId: users.realtor1.userId, legalEntityId: users.llcId, status: "draft", openedAt: new Date(), parties: { create: { clientId: foreign.id, partyRole: "buyer" } } } });
    expect((await pickCalendarLinks(users.realtor1, { type: "needId" })).map(n => n.id)).toContain(ownNeed.id);
    expect((await pickCalendarLinks(users.realtor1, { type: "needId" })).map(n => n.id)).not.toContain(foreignNeed.id);
    expect(await pickCalendarLinks(users.realtor1, { type: "dealId" })).toEqual([]);
    const response = await linksGET(apiRequest("GET", "/api/v1/calendar/links?type=clientId", { cookie: await sessionCookieFor(users.realtor1) }), routeParams({}));
    expect(response.status).toBe(200);
    expect(await response.text()).not.toContain("Скрытый клиент");
    const start = new Date(), end = new Date(+start + 3600000);
    const e = await saveCalendarEvent(users.realtor1, { title: "Встреча", clientId: own.id, startAt: start.toISOString(), endAt: end.toISOString(), recurrenceRule: "FREQ=WEEKLY;BYDAY=MO,TH;COUNT=4" });
    const dto = await getCalendarEvent(users.realtor1, e.id);
    expect("linked" in dto && dto.linked.clientId?.label).toBe("Доступный клиент");
    const items = await listCalendar(users.realtor1, { from: start.toISOString(), to: new Date(+start + 30 * 86400000).toISOString(), type: "calendar_event" });
    expect(items).toHaveLength(4);
  });
  it("reconstructs useful notification text and removes context immediately after client reassignment", async () => {
    const c = await makeClient(users.realtor1, { displayName: "Синтетический клиент уведомления" });
    const task = await createTask(users.realtor1, { title: "Уточнить бюджет клиента", taskType: "call_or_contact", dueAt: new Date(Date.now()-1000).toISOString(), links: { clientIds: [c.id] } });
    await generateNotifications();
    await db.notification.updateMany({ where: { sourceId: task.id }, data: { title: "НЕ ДОВЕРЯТЬ СОХРАНЁННОМУ ТЕКСТУ", link: "/clients/foreign" } });
    const before = await listNotifications(users.realtor1, {});
    expect(before.items[0]?.title).toContain("Синтетический клиент уведомления");
    expect(before.items[0]?.detail).toContain("Срок:");
    expect(before.items[0]?.link).toBe(`/tasks/${task.id}`);
    await db.client.update({ where: { id: c.id }, data: { responsibleUserId: users.realtor2.userId } });
    const after = JSON.stringify(await listNotifications(users.realtor1, {}));
    expect(after).not.toContain("Синтетический клиент уведомления");
    expect(after).not.toContain("Уточнить бюджет клиента");
    expect(after).not.toContain("НЕ ДОВЕРЯТЬ");
  });
  it("client overview includes need-only tasks and merges four interaction kinds to the latest five", async () => {
    const c = await makeClient(users.realtor1), n = await makeNeed(users.realtor1, c.id), p = await makeProperty(users.realtor1);
    const task = await createTask(users.realtor1, { title: "Задача только по потребности", taskType: "other", dueAt: new Date().toISOString(), links: { needIds: [n.id] } });
    await scheduleShowing(users.realtor1, { clientNeedId: n.id, propertyId: p.id, scheduledAt: new Date(Date.now()+3600000).toISOString() });
    await db.commercialOffer.create({ data: { clientNeedId: n.id, title: "Обзорное КП", responsibleUserId: users.realtor1.userId, createdBy: users.realtor1.userId, status: "draft" } });
    await db.communication.create({ data: { clientId: c.id, authorUserId: users.realtor1.userId, communicationType: "call", occurredAt: new Date(), comment: "Зафиксирован звонок" } });
    const tasks = await listTasksLinkedTo(users.realtor1, { clientId: c.id }, { includeIndirectClient: true });
    expect(tasks.map(t => t.id)).toContain(task.id);
    const interactions = await getClientRecentInteractions(users.realtor1, c.id);
    expect(interactions).toHaveLength(5);
    expect(new Set(interactions.map(e => e.kind))).toEqual(new Set(["task", "showing", "offer", "communication"]));
    expect(interactions.every((e, i) => !i || +interactions[i-1]!.at >= +e.at)).toBe(true);
    await expect(getClientRecentInteractions(users.realtor2, c.id)).rejects.toMatchObject({ code: "NOT_FOUND" });
  });
});
